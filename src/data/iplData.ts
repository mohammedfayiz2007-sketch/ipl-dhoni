/**
 * Automatically compile all configured team rosters into the single centralized player database.
 */
export function generatePlayersFromRoster(rosterConfig: Record<string, TeamRosterBaseline>): Player[] {
  const allPlayers: Player[] = [];
  const registeredIds = new Set<string>();

  for (const teamKey of Object.keys(rosterConfig)) {
    const team = rosterConfig[teamKey];
    for (const p of team.players) {
      let uniqueId = generatePlayerId(team.teamId, p.name);
      if (registeredIds.has(uniqueId)) {
        uniqueId = `${uniqueId}_${Date.now()}`;
      }
      registeredIds.add(uniqueId);

      allPlayers.push({
        id: uniqueId,
        name: p.name,
        country: p.country,
        isOverseas: p.isOverseas,
        role: p.role,
        battingStyle: p.battingStyle,
        bowlingStyle: p.bowlingStyle,
        basePrice: p.basePrice,
        previousTeam: team.teamCode,
        teamId: team.teamId,
        teamName: team.teamName,
        imageUrl: p.imageUrl,
        iplStats: p.iplStats,
        marquee: p.marquee,
        set: p.set,
        status: 'available',
      });
    }
  }

  return allPlayers;
}

