/**
 * Automatically generate a clean, unique player ID from team ID and player name.
 */
export function generatePlayerId(teamId: string, playerName: string): string {
  const sanitized = playerName
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '');
  return `${teamId}_${sanitized}`;
}

