export function calculateNextBid(currentBid: number): number {
  if (currentBid <= 0) return 2.0;
  if (currentBid < 1.0) {
    return Number((currentBid + 0.05).toFixed(2));
  } else if (currentBid < 2.0) {
    return Number((currentBid + 0.1).toFixed(2));
  } else if (currentBid < 5.0) {
    return Number((currentBid + 0.2).toFixed(2));
  } else if (currentBid < 10.0) {
    return Number((currentBid + 0.25).toFixed(2));
  } else if (currentBid < 20.0) {
    return Number((currentBid + 0.5).toFixed(2));
  } else {
    return Number((currentBid + 1.0).toFixed(2));
  }
}

export function formatCrores(amount: number): string {
  if (amount >= 1.0) {
    return `₹${amount.toFixed(2)} Cr`;
  }
  const lakhs = Math.round(amount * 100);
  return `₹${lakhs} L`;
}
